const assert = require('node:assert/strict')
const ts = require('typescript')
require.extensions['.ts'] = (module, filename) => module._compile(ts.transpileModule(require('node:fs').readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, esModuleInterop: true } }).outputText, filename)

const { decideCommandPermission, getCommandTemplate } = require('../src/shared/permission-policy.ts')
const { parseCommandProposalArgs } = require('../src/shared/command-proposal.ts')

assert.equal(getCommandTemplate('npm_typecheck').display, 'npm run typecheck')
assert.equal(getCommandTemplate('unknown'), null)
const allowed = decideCommandPermission({ template: 'npm_typecheck', reason: '检查类型' }, { kind: 'project', snapshotId: 'snapshot-30' })
assert.deepEqual(allowed, { risk: 'command', approval: 'user', allowed: true, scope: { kind: 'project', snapshotId: 'snapshot-30' } })
const missing = decideCommandPermission({ template: 'npm_typecheck', reason: '检查类型' }, null)
assert.equal(missing.allowed, false)
assert.match(missing.reason, /项目快照/)
assert.equal(parseCommandProposalArgs({ template: 'npm_typecheck', reason: '检查类型', cwd: 'D:\\' }), null)
console.log('Lesson 30 policy checks passed: shared template, approval boundary, project scope, and strict proposal parsing.')
